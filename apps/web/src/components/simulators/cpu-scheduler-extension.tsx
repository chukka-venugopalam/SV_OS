interface Proc {
  id: string;
  arrival: number;
  burst: number;
  priority: number;
}
const PROCESSES: Proc[] = [
  { id: 'P1', arrival: 0, burst: 8, priority: 3 },
  { id: 'P2', arrival: 1, burst: 4, priority: 1 },
  { id: 'P3', arrival: 2, burst: 9, priority: 4 },
  { id: 'P4', arrival: 3, burst: 5, priority: 2 },
];

interface GanttBlock {
  id: string;
  start: number;
  end: number;
}

function simulateSJF(processes: Proc[]): {
  gantt: GanttBlock[];
  waitTimes: Record<string, number>;
} {
  const remaining = [...processes];
  const gantt: GanttBlock[] = [];
  let time = 0;
  const completion: Record<string, number> = {};
  while (remaining.length > 0) {
    const available = remaining.filter((p) => p.arrival <= time);
    if (available.length === 0) {
      time = Math.min(...remaining.map((p) => p.arrival));
      continue;
    }
    available.sort((a, b) => a.burst - b.burst);
    const next = available[0];
    gantt.push({ id: next.id, start: time, end: time + next.burst });
    time += next.burst;
    completion[next.id] = time;
    remaining.splice(remaining.indexOf(next), 1);
  }
  const waitTimes: Record<string, number> = {};
  processes.forEach((p) => {
    waitTimes[p.id] = completion[p.id] - p.arrival - p.burst;
  });
  return { gantt, waitTimes };
}

function simulateSRTF(processes: Proc[]): {
  gantt: GanttBlock[];
  waitTimes: Record<string, number>;
} {
  const remainingBurst: Record<string, number> = {};
  processes.forEach((p) => {
    remainingBurst[p.id] = p.burst;
  });
  const completion: Record<string, number> = {};
  const gantt: GanttBlock[] = [];
  let time = 0;
  let lastId: string | null = null;
  let blockStart = 0;
  const totalWork = processes.reduce((s, p) => s + p.burst, 0);
  let done = 0;

  while (done < totalWork) {
    const available = processes.filter((p) => p.arrival <= time && remainingBurst[p.id] > 0);
    if (available.length === 0) {
      time++;
      continue;
    }
    available.sort((a, b) => remainingBurst[a.id] - remainingBurst[b.id]);
    const cur = available[0];
    if (cur.id !== lastId) {
      if (lastId !== null) gantt.push({ id: lastId, start: blockStart, end: time });
      lastId = cur.id;
      blockStart = time;
    }
    remainingBurst[cur.id]--;
    done++;
    time++;
    if (remainingBurst[cur.id] === 0) completion[cur.id] = time;
  }
  if (lastId !== null) gantt.push({ id: lastId, start: blockStart, end: time });
  // merge adjacent blocks with the same id (can happen if a process runs uninterrupted across the loop's per-tick granularity)
  const merged: GanttBlock[] = [];
  for (const b of gantt) {
    if (
      merged.length > 0 &&
      merged[merged.length - 1].id === b.id &&
      merged[merged.length - 1].end === b.start
    ) {
      merged[merged.length - 1].end = b.end;
    } else merged.push({ ...b });
  }
  const waitTimes: Record<string, number> = {};
  processes.forEach((p) => {
    waitTimes[p.id] = completion[p.id] - p.arrival - p.burst;
  });
  return { gantt: merged, waitTimes };
}

function simulatePriority(
  processes: Proc[],
  useAging: boolean,
): { gantt: GanttBlock[]; waitTimes: Record<string, number> } {
  const remaining = processes.map((p) => ({
    ...p,
    effectivePriority: p.priority,
    waitedSince: p.arrival,
  }));
  const gantt: GanttBlock[] = [];
  let time = 0;
  const completion: Record<string, number> = {};
  const AGING_RATE = 3; // every 3 time units waiting, priority improves by 1 (lower number = higher priority)

  while (remaining.length > 0) {
    const available = remaining.filter((p) => p.arrival <= time);
    if (available.length === 0) {
      time = Math.min(...remaining.map((p) => p.arrival));
      continue;
    }
    if (useAging) {
      available.forEach((p) => {
        const waited = time - p.waitedSince;
        p.effectivePriority = Math.max(1, p.priority - Math.floor(waited / AGING_RATE));
      });
    }
    available.sort((a, b) => a.effectivePriority - b.effectivePriority);
    const next = available[0];
    gantt.push({ id: next.id, start: time, end: time + next.burst });
    time += next.burst;
    completion[next.id] = time;
    remaining.splice(
      remaining.findIndex((p) => p.id === next.id),
      1,
    );
  }
  const waitTimes: Record<string, number> = {};
  processes.forEach((p) => {
    waitTimes[p.id] = completion[p.id] - p.arrival - p.burst;
  });
  return { gantt, waitTimes };
}

function avgWait(waitTimes: Record<string, number>): number {
  const vals = Object.values(waitTimes);
  return vals.reduce((a, b) => a + b, 0) / vals.length;
}

function GanttChart({ gantt, revealedUpTo }: { gantt: GanttBlock[]; revealedUpTo: number }) {
  const totalTime = Math.max(...gantt.map((b) => b.end), 1);
  const idColor: Record<string, string> = {};
  PROCESSES.forEach((p, i) => {
    idColor[p.id] = PROCESS_COLORS[i % PROCESS_COLORS.length];
  });

  return (
    <div>
      <div
        style={{
          display: 'flex',
          height: 40,
          borderRadius: 6,
          overflow: 'hidden',
          border: `1.5px solid ${COLORS.line}`,
        }}
      >
        {gantt.map((b, i) => {
          const revealed = i < revealedUpTo;
          return (
            <div
              key={i}
              style={{
                width: `${((b.end - b.start) / totalTime) * 100}%`,
                background: revealed ? idColor[b.id] : COLORS.panel,
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                fontSize: 11,
                fontWeight: 700,
                color: revealed ? '#fff' : COLORS.inkSoft,
                borderRight: i < gantt.length - 1 ? '1px solid #fff' : 'none',
              }}
            >
              {revealed ? b.id : ''}
            </div>
          );
        })}
      </div>
      <div
        style={{
          display: 'flex',
          justifyContent: 'space-between',
          fontSize: 9.5,
          color: COLORS.inkSoft,
          marginTop: 3,
        }}
      >
        <span>t=0</span>
        <span>t={totalTime}</span>
      </div>
    </div>
  );
}

// ============================= SJF MODE =============================
export function SjfMode() {
  const { gantt, waitTimes } = simulateSJF(PROCESSES);
  const [revealed, setRevealed] = useState(0);
  return (
    <div>
      <p style={{ fontSize: 13.5, color: COLORS.inkSoft, lineHeight: 1.6, margin: '0 0 14px' }}>
        Shortest Job First (non-preemptive): whenever the CPU is free, pick whichever AVAILABLE
        process has the shortest total burst time. Once started, a process runs to completion
        without interruption.
      </p>
      <table style={{ borderCollapse: 'collapse', fontSize: 12, marginBottom: 14 }}>
        <thead>
          <tr>
            <th style={{ padding: '2px 8px' }} />
            <th style={{ padding: '2px 8px' }}>Arrival</th>
            <th style={{ padding: '2px 8px' }}>Burst</th>
          </tr>
        </thead>
        <tbody>
          {PROCESSES.map((p) => (
            <tr key={p.id}>
              <td style={{ padding: '2px 8px', fontWeight: 700 }}>{p.id}</td>
              <td style={{ padding: '2px 8px' }}>{p.arrival}</td>
              <td style={{ padding: '2px 8px' }}>{p.burst}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <GanttChart gantt={gantt} revealedUpTo={revealed} />
      <div style={{ display: 'flex', gap: 8, marginTop: 14, marginBottom: 10 }}>
        <Btn
          variant="primary"
          onClick={() => setRevealed((r) => Math.min(gantt.length, r + 1))}
          disabled={revealed >= gantt.length}
        >
          Reveal next block
        </Btn>
        <Btn variant="ghost" onClick={() => setRevealed(0)}>
          Reset
        </Btn>
      </div>
      {revealed >= gantt.length && (
        <div
          style={{
            fontFamily: 'ui-monospace, monospace',
            fontSize: 13,
            color: COLORS.teal,
            fontWeight: 700,
          }}
        >
          Average waiting time: {avgWait(waitTimes).toFixed(2)}
        </div>
      )}
      <Callout>
        <strong>Common mistake:</strong> picking the shortest job among ALL processes, including
        ones that haven't arrived yet. SJF only considers processes that have actually ARRIVED by
        the current time — a shorter job that arrives later doesn't retroactively interrupt what's
        already running.
      </Callout>
    </div>
  );
}

