// ============================= MULTILEVEL QUEUE MODE =============================
export function MultilevelQueueMode() {
  const systemQueue = PROCESSES.filter((p) => p.priority <= 2); // "system" queue: higher priority processes
  const userQueue = PROCESSES.filter((p) => p.priority > 2); // "user" queue: lower priority processes
  const [phase, setPhase] = useState(0);

  return (
    <div>
      <p style={{ fontSize: 13.5, color: COLORS.inkSoft, lineHeight: 1.6, margin: '0 0 14px' }}>
        Processes are split into separate fixed queues based on their type — here, a "system" queue
        (priority 1-2) and a "user" queue (priority 3-4). Each queue can use its OWN scheduling rule
        internally, but the queues themselves have a fixed priority: the system queue is ALWAYS
        fully drained before the user queue gets any CPU time at all.
      </p>

      <div style={{ display: 'flex', gap: 20, marginBottom: 16, flexWrap: 'wrap' }}>
        <div style={{ flex: 1, minWidth: 200 }}>
          <div
            style={{
              fontSize: 12.5,
              fontWeight: 700,
              marginBottom: 8,
              color: phase === 0 ? COLORS.teal : COLORS.ink,
            }}
          >
            System queue (runs first, always)
          </div>
          <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap' }}>
            {systemQueue.map((p) => (
              <div
                key={p.id}
                style={{
                  padding: '8px 12px',
                  borderRadius: 6,
                  background: phase >= 0 ? COLORS.tealSoft : COLORS.panel,
                  border: `1.5px solid ${COLORS.teal}`,
                  fontFamily: 'ui-monospace, monospace',
                  fontSize: 12,
                }}
              >
                {p.id} (burst {p.burst})
              </div>
            ))}
          </div>
        </div>
        <div style={{ flex: 1, minWidth: 200 }}>
          <div
            style={{
              fontSize: 12.5,
              fontWeight: 700,
              marginBottom: 8,
              color: phase === 1 ? COLORS.teal : COLORS.ink,
            }}
          >
            User queue (only runs once system queue is empty)
          </div>
          <div style={{ display: 'flex', gap: 6, flexWrap: 'wrap' }}>
            {userQueue.map((p) => (
              <div
                key={p.id}
                style={{
                  padding: '8px 12px',
                  borderRadius: 6,
                  background: phase >= 1 ? COLORS.amberSoft : COLORS.panel,
                  border: `1.5px solid ${phase >= 1 ? COLORS.amber : COLORS.line}`,
                  fontFamily: 'ui-monospace, monospace',
                  fontSize: 12,
                  opacity: phase >= 1 ? 1 : 0.5,
                }}
              >
                {p.id} (burst {p.burst})
              </div>
            ))}
          </div>
        </div>
      </div>

      {phase === 0 && (
        <div style={{ fontSize: 13, color: COLORS.ink, marginBottom: 14 }}>
          The system queue is currently being serviced (e.g. using SJF or FCFS internally). Every
          process here finishes before the user queue is even considered.
        </div>
      )}
      {phase >= 1 && (
        <div style={{ fontSize: 13, color: COLORS.ink, marginBottom: 14 }}>
          System queue fully drained — the user queue can now finally run. Even though these
          processes may have arrived long ago, they had to wait for the ENTIRE system queue first.
        </div>
      )}

      <div style={{ display: 'flex', gap: 8 }}>
        <Btn
          variant="primary"
          onClick={() => setPhase((p) => Math.min(1, p + 1))}
          disabled={phase >= 1}
        >
          Advance to next queue
        </Btn>
        <Btn variant="ghost" onClick={() => setPhase(0)}>
          Reset
        </Btn>
      </div>

      <Callout>
        <strong>Common mistake:</strong> assuming multilevel queue scheduling is "fair" because each
        queue has its own rule internally. The QUEUE-to-QUEUE priority is fixed and typically NOT
        preemptible by aging — a user-queue process can wait indefinitely if the system queue keeps
        receiving new work, since this scheme (unlike aging priority scheduling) has no built-in
        mechanism to promote a process to a higher queue.
      </Callout>
    </div>
  );
}

